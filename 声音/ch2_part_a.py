def c(x):
    return x + O


def P(note, x, rel, pan=0.0, verb=(1.6, 0.22), **kw):
    """语法糖：place(…, c(x), …)，x 为章内秒"""
    place(note, c(x), rel, pan, verb)


def lay(bus, sig, x, gain, pan=0.0):
    bus.add(sig, c(x), gain, pan)


def combo(parts, length=2.0):
    """把同一下的几个声音合成一个信号：parts=[(信号, 偏移秒, 增益)]，当作一个点缀放。"""
    n = int(length * SR); z = np.zeros(n)
    for sig, off, g in parts:
        i = int(off * SR); k = min(len(sig), n - i); z[i:i + k] += g * sig[:k]
    return z


def snap(x, anchor, grid):
    return anchor + round((x - anchor) / grid) * grid


def loop_out(bus, t0, t1, rel, cut, rt=(1.2, 0.18), ducks=()):
    """循环成品：加一点混响，按 t0–t1（章内秒）的手机外放响度归一到 REF+rel，在 cut（章内秒）一刀切断。
    ducks = [(章内秒, 压低 dB, 保持秒)]：重拍/揭示那一拍循环让路（前 0.05 秒压下去，保持后 0.3 秒回来）。"""
    y = reverb(bus.x, *rt)
    y = level_bus(y, c(t0), c(t1), rel)
    env = np.ones(y.shape[1])
    for td, db, hold in ducks:
        a, b = int((c(td) - 0.05) * SR), int((c(td) + hold) * SR)
        r = int(0.3 * SR); g = 10 ** (-db / 20)
        shape = np.concatenate([np.linspace(1, g, int(0.04 * SR)), np.full(max(0, b - a - int(0.04 * SR)), g), np.linspace(g, 1, r)])
        e0 = np.ones(y.shape[1]); n_ = min(len(shape), len(e0) - a); e0[a:a + n_] = shape[:n_]
        env = np.minimum(env, e0)
    y = y * env
    y[:, int(c(cut) * SR):] = 0
    out.x += y


