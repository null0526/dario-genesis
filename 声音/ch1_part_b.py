"""第一章 155.17–191.2 秒声音点缀（部分 B：J1 → 诺亚 → 诺亚双标 → J2），独立作曲。
时间＝全片秒＝第一章秒。旁白时间用 outputs/chapter1-r13/data.js（现行）；画面事件来自各镜头 EV，并用 kit.frame_trace / 1fps~15fps 联系表在成片 全片-r3.mp4 上核过：
  155.17–158.53  J1 西方地区：画面只有静止标题和缓慢横移，没有发生任何事 → 静默（静默是“西方”这一页的开场）
  158.53         切进诺亚：从灰色控制台切到琥珀色海床，一个温暖的单音
  163.83–165.5   “各存两份”：七种生物逐种复制，每种一对音（原件＋副本，上行五声）
  166.0–167.0    “带着离线副本”：副本向槽位聚拢，一串越来越密的上行小音
  167.2          方舟浮起：D 大和弦绽开一次（水面托起船）
  168.55         “封号”天光熄灭：和弦随灯一起收掉，一声不凶的低闷击（躲过去了，所以不是三全音）
  169.45–170.6   切到纸质台账（东方）：纸滑入、诺亚条目到位
  171.28/172.58  台账上两枚红印“批量爬取”“规避封禁”：两次重盖章（三全音，一次比一次高一点）
  174.17         切到控制台（西方）：留白；与上面的盖章形成反差
  175.13–175.65  “灾备做得好”胶囊出现、逐字亮起：一串愉快的小音，收在玻璃双音上
  179.72         “良好”浮现：两个玻璃音
  181.15         “已终止”红胶囊：A4→D4 两声下行冷提示（与 69.0“额度耗尽”同一手法）
  182.0–182.95   “驳回/通过”按钮出现、鼠标点击“通过”：点击＋批准音
  183.2–184.25   转圈等待：越来越高的拨弦小音
  184.32         “已恢复”：垫音和弦＋玻璃音（复活）
  186.5          “耶稣”名字出现：轻一点的钟（与 121.35 原罪那口低钟对称，高八度、轻很多）
  188.62         “3 天”：干巴巴一声拨弦
  189.6          章末：D–A 空五度落下，随画面淡出，191.0 前收完"""
import os, sys
import numpy as np
from scipy.io import wavfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kit import *

DUR = 194.0
out = Bus(DUR)
place = make_place(out)
T0 = 155.17   # 本段起点：之前的声音归协调者


def at(t, what):
    assert t >= T0 - 1e-6, (t, what)
    return t


# ================= 155.17–158.53 J1：静默 =================

# ================= 158.53 诺亚进场 =================
place(mallet(m('D4'), 2.0), at(158.62, 'noah in'), -7, -0.1, (2.4, 0.35))
place(glass(m('A5'), 2.4, 3.0, 1.0), 158.70, -9, 0.25, (2.4, 0.35))

# ================= 163.83– 各存两份：七种生物逐种复制 =================
sp = ['D5', 'E5', 'F#5', 'G5', 'A5', 'B5', 'C#6']   # r2 协调者：西方段用完整大调音阶（含 4、7 级），去掉五声的东方味
for i, nm in enumerate(sp):
    t = 163.83 + 0.27 * i
    pan = -0.55 + 0.18 * i
    place(pluck(m(nm), 1.0, 0.55), t, -10, pan, (1.3, 0.2))                 # 原件
    place(pluck(m(nm), 0.8, 0.35), t + 0.10, -14, pan + 0.15, (1.3, 0.2))     # 副本：同音更柔，晚一点点

# ================= 166.0–167.1 带着离线副本：向槽位聚拢 =================
gather = ['D4', 'F#4', 'A4', 'C#5', 'D5', 'E5', 'F#5', 'G5', 'A5', 'C#6', 'D6', 'F#6']
t = 166.0
for i, nm in enumerate(gather):
    place(pluck(m(nm), 0.8, 0.5), t, -13 + 0.25 * i, -0.6 + 1.2 * ((i * 5) % 12) / 11, (1.2, 0.2))
    t += max(0.06, 0.20 * 0.84 ** i)

# ================= 167.2 方舟浮起 → 168.8 灯灭收掉 =================
ark = pad([m('D3'), m('A3'), m('D4'), m('F#4'), m('A4')], 1.9, a=0.35, r=0.9, cutoff=900, cutoff_end=2600)
place(ark, 167.15, -7, 0, (2.4, 0.4))
place(glass(m('A6'), 2.0, 3.5, 1.0), 167.35, -10, 0.3, (2.4, 0.4))
place(stamp([m('D3'), m('A3')]), 168.55, -4, 0, (2.2, 0.3))                                   # 封号：灯灭的一声低闷击（纯五度，不凶）

# ================= 169.43 切到台账（东方） =================
place(paper(0.5, 900, 4000), 169.46, -6, 0.1, (0.8, 0.12))
place(paper(0.7, 600, 2500), 169.75, -9, -0.2, (0.8, 0.12))                       # 台账向左滑
place(knock_note(m('D4'), 1.4), 170.55, -8, -0.4, (1.8, 0.25))                    # 诺亚条目到位
place(stamp([m('D4'), m('G#4')]), 171.28, -1, 0.1, (1.8, 0.25))                   # 红印一：批量爬取
place(stamp([m('E4'), m('A#4')]), 172.58, -1.5, 0.15, (1.8, 0.25))                # 红印二：规避封禁

# ================= 174.17 西方控制台：留白，然后“灾备做得好” =================
place(glass(m('A5'), 1.2, 3.0, 1.0), 175.13, -10, 0.3, (1.2, 0.2))                 # 胶囊出现
for nm, tt, pn in [('A5', 175.27, -0.1), ('B5', 175.37, 0.0), ('C#6', 175.50, 0.1), ('D6', 175.60, 0.2)]:   # 导音 C# 解决到 D
    place(mallet(m(nm), 0.7), tt, -11, pn, (1.2, 0.2))                              # 逐字亮起
place(glass(m('D6'), 2.0, 3.5, 1.0) + 0.7 * glass(m('A6'), 2.0, 3.5, 1.0), 175.66, -6, 0.2, (2.2, 0.35))   # 灾备做得好：双音收束

# ================= 176.84– J2 =================
place(glass(m('A5'), 1.6, 3.5, 1.2), 179.72, -6, -0.1, (2.0, 0.3))                  # “良好”浮现
place(glass(m('D6'), 1.8, 3.5, 1.2), 179.84, -8, 0.15, (2.0, 0.3))
place(beep(m('A4'), 0.22, 0.4), 181.15, -6, 0, (1.0, 0.15))                         # “已终止”
place(beep(m('D4'), 0.45, 0.4), 181.40, -6, 0, (1.4, 0.2))
place(tick(0.04, 2400), 182.00, -9, 0.2, (0.6, 0.1))                                # 驳回/通过按钮出现
place(tick(0.04, 2900), 182.13, -9, 0.3, (0.6, 0.1))
place(click(), 182.95, -7, 0.3, (0.6, 0.1))                                         # 点击“通过”
place(beep(m('D5'), 0.14, 0.15), 183.01, -8, 0.3, (1.2, 0.2))
spin = ['A4', 'B4', 'C#5', 'D5', 'E5', 'F#5', 'G5']   # 停在 G（下属），接下面的“阿们终止”                                  # 转圈等待：越来越高
for i, nm in enumerate(spin):
    place(pluck(m(nm), 0.7, 0.4), 183.18 + 0.165 * i - 0.004 * i * i, -13 + 0.4 * i, 0.3 - 0.1 * i, (1.0, 0.15))
amen = pad([m('G2'), m('D3'), m('G3'), m('B3'), m('D4')], 0.85, a=0.06, r=0.25, cutoff=1200)      # 阿们终止 IV→I：先 G 大
place(amen, 184.32, -4, 0, (2.6, 0.4))
res = pad([m('D3'), m('A3'), m('D4'), m('F#4'), m('A4')], 3.2, a=0.08, r=1.8, cutoff=1000, cutoff_end=3200)
place(res, 185.12, -4, 0, (2.6, 0.4))                                               # 再落 D 大：教堂的“阿们”                                               # 已恢复：复活的和弦
place(glass(m('D6'), 2.4, 3.5, 1.0) + 0.7 * glass(m('A6'), 2.4, 3.5, 1.0), 184.32, -6, 0.1, (2.4, 0.35))
place(church_bell(m('D4'), 4.0), 186.50, -7, 0, (2.8, 0.4))                         # “耶稣”：轻钟（原罪那口是 D3 −2）
place(pluck(m('D4'), 0.5, 0.25), 188.62, -7, 0, (0.8, 0.12))                        # “3 天”：干巴巴一声
place(mallet(m('D4'), 2.0) + 0.5 * mallet(m('F#4'), 2.0) + 0.6 * mallet(m('A4'), 2.0), 189.60, -9, 0, (3.0, 0.4))  # 章末：空五度，随淡出落下

n = int(DUR * SR)
mix = out.x[:, :n].copy()
tt = np.arange(n) / SR
mix *= np.clip((191.0 - tt) / 0.6, 0, 1)             # 191.2 之后是第二章：本段在 191.0 前收完
mix[:, :int(T0 * SR)] = 0
wavfile.write(__file__.replace('ch1_part_b.py', 'ch1-part-b-music.wav'), SR, mix.T.astype(np.float32))
pk = peaks_per_second(mix)
print('ok', round(n / SR, 2), 'peak', round(float(np.abs(mix).max()), 3))
print({i + 150: p for i, p in enumerate(pk[150:192]) if p > 0.001})
